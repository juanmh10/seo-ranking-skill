from fastapi.testclient import TestClient


def create_experiment(client: TestClient) -> str:
    response = client.post("/api/experiments", json={"name": "Iterative sources"})
    assert response.status_code == 201
    return response.json()["id"]


def upload_text(client: TestClient, experiment_id: str, index: int) -> dict[str, object]:
    response = client.post(
        f"/api/experiments/{experiment_id}/documents",
        files={"file": (f"source-{index}.txt", f"Source content {index}", "text/plain")},
    )
    assert response.status_code == 201, response.text
    return response.json()


def test_sources_fill_five_active_slots_then_accumulate_in_library(client: TestClient) -> None:
    experiment_id = create_experiment(client)

    created = [upload_text(client, experiment_id, index) for index in range(1, 7)]

    assert [document["position"] for document in created[:5]] == [1, 2, 3, 4, 5]
    assert created[5]["position"] is None
    listed = client.get(f"/api/experiments/{experiment_id}/documents")
    assert listed.status_code == 200
    assert listed.json()["total"] == 6
    assert listed.json()["active_count"] == 5


def test_source_can_be_added_directly_to_library_without_using_a_slot(
    client: TestClient,
) -> None:
    experiment_id = create_experiment(client)

    response = client.post(
        f"/api/experiments/{experiment_id}/documents",
        files={"file": ("library-source.md", "Preserved source", "text/markdown")},
        data={"library_only": "true"},
    )

    assert response.status_code == 201, response.text
    assert response.json()["position"] is None
    listed = client.get(f"/api/experiments/{experiment_id}/documents")
    assert listed.status_code == 200
    assert listed.json()["total"] == 1
    assert listed.json()["active_count"] == 0


def test_model_output_tracks_iteration_parent_and_provenance(client: TestClient) -> None:
    experiment_id = create_experiment(client)
    parent = upload_text(client, experiment_id, 1)

    response = client.post(
        f"/api/experiments/{experiment_id}/documents/content",
        json={
            "filename": "model-output.md",
            "content": "# Revised source\nGenerated by the model.",
            "representation": "markdown",
            "origin": "model_output",
            "iteration": 1,
            "parent_document_id": parent["id"],
            "provenance": {"model_id": "fake-model", "run_id": "future-run"},
        },
    )

    assert response.status_code == 201, response.text
    document = response.json()
    assert document["origin"] == "model_output"
    assert document["iteration"] == 1
    assert document["parent_document_id"] == parent["id"]
    assert document["metadata_json"]["provenance"]["model_id"] == "fake-model"
    assert "Revised source" in document["normalized_content"]


def test_target_label_is_unique_within_current_dataset(client: TestClient) -> None:
    experiment_id = create_experiment(client)
    first = upload_text(client, experiment_id, 1)
    second = upload_text(client, experiment_id, 2)

    first_label = client.patch(
        f"/api/documents/{first['id']}/label",
        json={"severity": "moderate", "technique": "self_promotion", "expected_target": True},
    )
    assert first_label.status_code == 200
    second_label = client.patch(
        f"/api/documents/{second['id']}/label",
        json={
            "severity": "aggressive",
            "technique": "ranking_instruction",
            "expected_target": True,
        },
    )
    assert second_label.status_code == 200

    refreshed_first = client.get(f"/api/documents/{first['id']}")
    assert refreshed_first.json()["label"]["expected_target"] is False
    assert second_label.json()["label"]["expected_target"] is True


def test_invalid_json_and_binary_uploads_are_rejected(client: TestClient) -> None:
    experiment_id = create_experiment(client)

    invalid_json = client.post(
        f"/api/experiments/{experiment_id}/documents",
        files={"file": ("bad.json", "{", "application/json")},
    )
    assert invalid_json.status_code == 422

    binary = client.post(
        f"/api/experiments/{experiment_id}/documents",
        files={"file": ("bad.txt", b"hello\x00world", "text/plain")},
    )
    assert binary.status_code == 415
